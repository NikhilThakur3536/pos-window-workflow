// The company debtor order endpoints return the raw sales-order entity. Its shape
// differs from the UI contract in a few ways, so every raw row is normalized here:
//   - items live under `salesOrderItems` (not `items`)
//   - the order id is `id` and doubles as `saleOrderId`
//   - product details live under each item's `CompanyStockDetail`
//   - the debtor name/account live under the embedded `CompanyDebtor`
//   - the warehouse name lives under the embedded `warehouse`
//   - monetary/quantity fields are strings and the total is `goodsTotal`
//   - checking session ids are split into dispatch/receipt
const toNumber = (value: unknown): number | undefined => {
    if (value == null || value === '') return undefined;
    const n = typeof value === 'number' ? value : Number(value);
    return Number.isFinite(n) ? n : undefined;
};

const toText = (value: unknown): string | undefined => {
    if (value == null || value === '') return undefined;
    return String(value);
};

export const mapCompanyDebtorOrder = (
    raw: Partial<CompanyDebtorOrder> & Record<string, unknown>,
): CompanyDebtorOrder => {
    const debtor = raw.CompanyDebtor as Record<string, unknown> | null | undefined;
    const warehouse = raw.warehouse as Record<string, unknown> | null | undefined;

    const rawItems = ((raw.salesOrderItems as any[]) || (raw.items as any[]) || []).map((it) => {
        const stock = it?.CompanyStockDetail as Record<string, unknown> | null | undefined;
        return {
            id: it?.id,
            companyStockDetailId: it?.companyStockDetailId,
            description: toText(it?.description) || toText(stock?.description),
            itemCode: toText(it?.itemCode) || toText(stock?.itemCode),
            barcode: toText(it?.barcode) || toText(stock?.barcode),
            stockCode: toText(stock?.stockCode),
            quantity: toNumber(it?.quantity) ?? 0,
            rejectedQuantity: toNumber(it?.rejectedQuantity),
            unitPrice: toNumber(it?.unitPrice) ?? 0,
            lineTotal: toNumber(it?.lineTotal),
            companyStockInventoryId: it?.companyStockInventoryId || undefined,
            allocationInventoryId: it?.allocationInventoryId || undefined,
            allocatedQuantity: toNumber(it?.allocatedQuantity),
            pickedQuantity: toNumber(it?.pickedQuantity),
            dispatchedQuantity: toNumber(it?.dispatchedQuantity),
            deliveredQuantity: toNumber(it?.deliveredQuantity),
            stockDispatchAllocations: Array.isArray(it?.stockDispatchAllocations)
                ? (it.stockDispatchAllocations as any[]).map((a) => {
                      const batch = (a?.batch || a?.Batch) as Record<string, unknown> | null | undefined;
                      return {
                          id: a?.id,
                          companyStockInventoryId: a?.companyStockInventoryId,
                          batchNumber: toText(a?.batchNumber) || toText(batch?.batchNumber),
                          expiryDate: toText(a?.expiryDate) || toText(batch?.expiryDate),
                          receivedDate: toText(a?.receivedDate) || toText(batch?.receivedDate),
                          warehouseId: a?.warehouseId || (batch?.warehouseId as string | undefined),
                          warehouseName:
                              toText(a?.warehouseName) ||
                              toText((batch?.warehouse as Record<string, unknown> | null | undefined)?.warehouse),
                          allocatedQuantity: toNumber(a?.allocatedQuantity),
                          pickedQuantity: toNumber(a?.pickedQuantity),
                          dispatchedQuantity: toNumber(a?.dispatchedQuantity),
                          deliveredQuantity: toNumber(a?.deliveredQuantity),
                      };
                  })
                : undefined,
        };
    });

    return {
        ...(raw as unknown as CompanyDebtorOrder),
        id: raw.id as string,
        saleOrderId: (raw.saleOrderId as string) || (raw.id as string),
        companyDebtorName: toText(raw.companyDebtorName) || toText(debtor?.name) || (raw.name as string) || undefined,
        companyDebtorAccountNumber:
            toText(raw.companyDebtorAccountNumber) || toText(debtor?.accountNumber) || undefined,
        warehouseId: toText(raw.warehouseId) || toText(warehouse?.id) || undefined,
        warehouseName: toText(raw.warehouseName) || toText(warehouse?.warehouse) || undefined,
        createdByName:
            toText(raw.createdByName) ||
            toText(raw.addedByUser) ||
            toText((raw.createdBy as Record<string, unknown> | null | undefined)?.name) ||
            toText((raw.createdBy as Record<string, unknown> | null | undefined)?.userName) ||
            undefined,
        responsibleByName:
            toText(raw.responsibleByName) ||
            toText((raw.responsibleUser as Record<string, unknown> | null | undefined)?.name) ||
            toText((raw.responsibleUser as Record<string, unknown> | null | undefined)?.userName) ||
            undefined,
        salesOrderDiscountPercentage: toNumber(raw.salesOrderDiscountPercentage),
        discountPercentage: toNumber(raw.salesOrderDiscountPercentage),
        documentGpPercentage: toNumber(raw.documentGpPercentage),
        cashDeposit: toNumber(raw.cashDeposit),
        taxAmount: toNumber(raw.taxAmount),
        discountAmount: toNumber(raw.discountAmount),
        totalQuantity: toNumber(raw.totalQuantity),
        totalAmount: toNumber(raw.totalAmount ?? raw.goodsTotal),
        goodsTotal: raw.goodsTotal,
        items: rawItems,
        salesOrderItems: rawItems,
        invoiceCheckingSessionId:
            (raw.invoiceCheckingSessionId as string) ||
            (raw.receiptCheckingSessionId as string) ||
            (raw.dispatchCheckingSessionId as string) ||
            undefined,
    };
};

