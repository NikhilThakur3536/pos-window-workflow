export async function getCompanyDebtorOrderList(
    props: CompanyDebtorOrderListFilters,
): Promise<GetCompanyDebtorOrderListResponse> {
    const res = await axiosInstance({
        url: apiUrls.companyDebtorOrder.all.url,
        method: apiUrls.companyDebtorOrder.all.method,
        data: props,
    });
    const data = res.data as GetCompanyDebtorOrderListResponse;
    return {
        ...data,
        data: {
            count: data?.data?.count ?? 0,
            rows: (data?.data?.rows || []).map((row) =>
                mapCompanyDebtorOrder(row as unknown as Record<string, unknown>),
            ),
        },
    };
}

export const useGetCompanyDebtorOrderList = (props: CompanyDebtorOrderListFilters) => {
    return useQuery({
        queryKey: [getApiKey(apiUrls.companyDebtorOrder), 'all', props],
        queryFn: async () => await getCompanyDebtorOrderList(props),
    });
};

export async function getCompanyDebtorOrderById(
    saleOrderId: string,
    companyDebtorId?: string,
): Promise<{ success: boolean; message: string; data: CompanyDebtorOrder }> {
    const res = await axiosInstance({
        url: apiUrls.companyDebtorOrder.get.url,
        method: apiUrls.companyDebtorOrder.get.method,
        data: { saleOrderId, ...(companyDebtorId ? { companyDebtorId } : {}) },
    });
    const data = res.data as { success: boolean; message: string; data: CompanyDebtorOrder };
    return {
        success: data?.success,
        message: data?.message,
        data: data?.data
            ? mapCompanyDebtorOrder(data.data as unknown as Record<string, unknown>)
            : (data?.data as CompanyDebtorOrder),
    };
}

export const useGetCompanyDebtorOrderById = (saleOrderId: string | null, companyDebtorId?: string) => {
    return useQuery({
        queryKey: [getApiKey(apiUrls.companyDebtorOrder), 'get', saleOrderId],
        enabled: !!saleOrderId,
        queryFn: async () => await getCompanyDebtorOrderById(saleOrderId as string, companyDebtorId),
    });
};

