// --------------------------------------- COMPANY DEBTOR ORDERS ---------------------------------------
//
// Company Debtor Orders is an offline ordering flow where a store (companyDebtor) submits orders to a
// distributor/head-office. Orders move through a lifecycle:
//   REQUESTED -> SCHEDULED -> ALLOCATED -> PICKED -> DISPATCHED -> DELIVERED  (or CANCELLED)
//
// Key conventions:
//   - companyDebtorId identifies the debtor/retail account (scope and filtering).
//   - saleOrderId identifies an existing order. Generic top-level `id` is not accepted.
//   - clientDocumentId: unique id generated by FE when creating an order.
//   - clientEventId: unique id for every update/workflow action.
//   - lifecycleVersion: value returned in the latest response; sent with every update/action.
//   - Action quantities are cumulative totals (not additional quantities).
//   - Delivery days use 1 = Monday .. 7 = Sunday.
//
// Note: `company-id` / `Authorization` headers are injected automatically by the axiosInstance
// interceptor; a companyDebtor (store) user is always restricted to their assigned companyDebtorId.

export const COMPANY_DEBTOR_ORDER_SOURCES = ['POS', 'WEB', 'MOBILE', 'EDI', 'MANUAL'] as const;
export type CompanyDebtorOrderSource = (typeof COMPANY_DEBTOR_ORDER_SOURCES)[number];

export const ORDER_LIFECYCLE_STATUSES = [
    'REQUESTED',
    'SCHEDULED',
    'PART_ALLOCATED',
    'ALLOCATED',
    'PART_PICKED',
    'PICKED',
    'PART_DISPATCHED',
    'DISPATCHED',
    'PART_DELIVERED',
    'DELIVERED',
    'DELIVERED_WITH_EXCEPTION',
    'CANCELLED',
] as const;
export type OrderLifecycleStatus = (typeof ORDER_LIFECYCLE_STATUSES)[number];

export const DELIVERY_FREQUENCIES = ['DAILY', 'ONCE_WEEKLY', 'TWICE_WEEKLY', 'WEEKLY', 'MONTHLY'] as const;
export type DeliveryFrequency = (typeof DELIVERY_FREQUENCIES)[number];

export const BATCH_ALLOCATION_STRATEGIES = ['AUTO', 'FEFO', 'FIFO'] as const;
export type BatchAllocationStrategy = (typeof BATCH_ALLOCATION_STRATEGIES)[number];

export const CHECK_DIRECTION = ['OUTGOING', 'INCOMING'] as const;
export type CheckDirection = (typeof CHECK_DIRECTION)[number];

