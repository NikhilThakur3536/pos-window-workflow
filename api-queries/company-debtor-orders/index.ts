export const createCompanyDebtorOrderSchema = z.object({
    clientDocumentId: z.string().min(1, 'Client document id is required'),
    companyDebtorId: z.string().min(1, 'Store is required'),
    warehouseId: z.string().optional(),
    orderSource: z.enum(COMPANY_DEBTOR_ORDER_SOURCES),
    requestedDeliveryDate: z.string().min(1, 'Requested delivery date is required'),
    salesMemo: z.string().optional(),
    items: z
        .array(
            z.object({
                companyStockDetailId: z.string().min(1, 'Product is required'),
                quantity: z.number().min(1, 'Quantity must be at least 1'),
                unitPrice: z.number().min(0),
            }),
        )
        .min(1, 'At least one item is required'),
});

export type CreateCompanyDebtorOrderInput = z.infer<typeof createCompanyDebtorOrderSchema>;

export async function createCompanyDebtorOrder(
    data: CreateCompanyDebtorOrderInput,
): Promise<{ success: boolean; message: string; data?: CompanyDebtorOrder }> {
    // A warehouse user's assigned warehouse is the inventory location for the order.
    // Only used when the dialog did not explicitly select one (store users keep "store default").
    const user = useAuthUser.getState().user;
    const assignedWarehouseId = user?.userType === 'WAREHOUSE-USER' ? user?.warehouseId : undefined;
    const payload = {
        ...data,
        ...(data.warehouseId || !assignedWarehouseId ? {} : { warehouseId: assignedWarehouseId }),
    };
    return (
        await axiosInstance({
            url: apiUrls.companyDebtorOrder.create.url,
            method: apiUrls.companyDebtorOrder.create.method,
            data: payload,
        })
    ).data;
}

export const useCreateCompanyDebtorOrder = () => {
    const queryClient = useQueryClient();
    return useMutation({
        mutationFn: createCompanyDebtorOrder,
        onSuccess: () => {
            queryClient.invalidateQueries({ queryKey: [getApiKey(apiUrls.companyDebtorOrder)] });
        },
    });
};

