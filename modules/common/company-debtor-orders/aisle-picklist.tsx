'use client';

import { useEffect, useMemo, useRef, useState } from 'react';
import { Button } from '@/components/ui/button';
import { Label } from '@/components/ui/label';
import { Badge } from '@/components/ui/badge';
import { Separator } from '@/components/ui/separator';
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '@/components/ui/select';
import { PageLoader } from '@/components/custom-components/PageLoader';
import { toast } from 'sonner';
import { CalendarClock, ChevronsUpDown, FileDown, Loader2, Printer } from 'lucide-react';
import { useReactToPrint } from 'react-to-print';
import { useAuthUser } from '@/stores/auth-user.store';
import { useDebtorList } from '@/api-queries/debtor';
import {
    useGetCompanyDebtorOrderById,
    useGetCompanyDebtorOrderList,
    type CompanyDebtorOrder,
} from '@/api-queries/company-debtor-orders';
import {
    PICKLIST_SORT_OPTIONS,
    PicklistSortBy,
    PicklistSummary,
    WarehousePicklistLine,
    useGenerateWarehousePicklist,
} from '@/api-queries/company/warehouse-location';
import { useGetWarehouses, type WarehouseDetails } from '@/api-queries/warehouse';
import SelectPopover from '@/components/select-popover';

const ORDER_PAGE_SIZE = 20;

// Orders in these states must never offer a picklist — there is nothing to walk.
const HIDDEN_ORDER_STATUSES = ['CANCELLED', 'DELETED'];

const AislePicklist = ({ initialOrderId }: { initialOrderId?: string }) => {
    const currentUser = useAuthUser((state) => state.user);
    const isStoreUser = currentUser?.userType === 'COMPANY-DEBTOR-USER';
    const myDebtorId = currentUser?.companyDebtorId || '';

    const [storeId, setStoreId] = useState(myDebtorId);
    const [orderId, setOrderId] = useState(initialOrderId || '');
    const [sortBy, setSortBy] = useState<PicklistSortBy>('AISLE');
    const [ordersLoaded, setOrdersLoaded] = useState(ORDER_PAGE_SIZE);

    const generateMut = useGenerateWarehousePicklist();
    const autoGeneratedRef = useRef(false);

    const printRef = useRef<HTMLDivElement>(null);
    const handlePrint = useReactToPrint({ contentRef: printRef });

    const { data: debtorsRes } = useDebtorList({ limit: 1000, offset: 0 });
    const stores = (debtorsRes?.data?.rows as any[]) || [];

    const { data: warehousesRes } = useGetWarehouses({ limit: 1000, offset: 0 });
    const warehouses: WarehouseDetails[] = useMemo(() => {
        const raw = warehousesRes?.data as WarehouseDetails[] | { rows?: WarehouseDetails[] } | undefined;
        return Array.isArray(raw) ? raw : raw?.rows || [];
    }, [warehousesRes]);

    const activeStoreId = isStoreUser ? myDebtorId : storeId;

    // When the screen is opened from an order (deep link), resolve that order so we can
    // pre-select its store and generate its picklist without the user searching for it.
    const deepLinkOrderQuery = useGetCompanyDebtorOrderById(initialOrderId || null);

    const ordersQuery = useGetCompanyDebtorOrderList({
        ...(activeStoreId ? { companyDebtorId: activeStoreId } : {}),
        limit: ordersLoaded,
        offset: 0,
    });

    const allOrders: CompanyDebtorOrder[] = ordersQuery?.data?.data?.rows || [];
    const orders = allOrders.filter((o) => !HIDDEN_ORDER_STATUSES.includes((o.lifecycleStatus || '').toUpperCase()));
    const orderCount = ordersQuery?.data?.data?.count || 0;

    const storeNameById = useMemo(() => {
        const map: Record<string, string> = {};
        stores.forEach((s: any) => {
            if (s?.id) map[s.id] = s.name || s.tradingAs || s.id;
        });
        return map;
    }, [stores]);
    const storeName = activeStoreId ? storeNameById[activeStoreId] || '—' : 'All stores';

    const selectedOrder = allOrders.find((o) => o.id === orderId) || deepLinkOrderQuery.data?.data || null;

    const allLines: WarehousePicklistLine[] = useMemo(() => {
        const data = generateMut.data?.data;
        return Array.isArray(data) ? data : data?.rows || [];
    }, [generateMut.data]);

    const picklistSummary: PicklistSummary | undefined = useMemo(() => {
        const data = generateMut.data?.data;
        return !Array.isArray(data) ? data?.summary : undefined;
    }, [generateMut.data]);

    const generatedWarehouseId = useMemo(() => {
        const data = generateMut.data?.data;
        return !Array.isArray(data) ? data?.warehouseId : undefined;
    }, [generateMut.data]);

    const warehouseName = useMemo(() => {
        if (!generatedWarehouseId) return '—';
        const match = warehouses.find((w) => w.id === generatedWarehouseId);
        return match?.warehouse || match?.name || generatedWarehouseId;
    }, [warehouses, generatedWarehouseId]);

    const linePath = (l: WarehousePicklistLine) => l.locationPath || l.displayPath || l.codePath || '';
    const isUnassigned = (l: WarehousePicklistLine) =>
        !l.warehouseLocationId || (linePath(l) || '').toUpperCase() === 'UNASSIGNED';

    // Keep BE's returned walking order untouched (screen, print and CSV all follow it). The aisle
    // comes from the allocated source inventory, not the receiving store.
    const orderedLines = useMemo(() => {
        const assigned = allLines.filter((l) => !isUnassigned(l));
        const unassigned = allLines.filter(isUnassigned);
        return { assigned, unassigned, rows: allLines };
    }, [allLines]);

    const generate = (overrideOrderId?: string) => {
        const targetOrderId = overrideOrderId || orderId;
        if (!targetOrderId) return toast.error('Select an order');
        generateMut.mutate(
            {
                sourceDocumentType: 'COMPANY_DEBTOR_ORDER',
                sourceDocumentId: targetOrderId,
                sortBy,
            },
            {
                onSuccess: (data) => {
                    const list = Array.isArray(data?.data) ? data.data : data?.data?.rows || [];
                    if (data.success) {
                        toast.success(`Picklist generated (${list.length} lines)`);
                    } else {
                        toast.error(data.message || 'Failed to generate picklist');
                    }
                },
                onError: (error: any) => {
                    toast.error(error?.response?.data?.message || 'Internal Server Error!');
                },
            },
        );
    };

    // Deep link: resolve the order's store, then generate once.
    useEffect(() => {
        if (!initialOrderId || autoGeneratedRef.current) return;
        const order = deepLinkOrderQuery.data?.data;
        if (!order) return;
        if (!isStoreUser && order.companyDebtorId) setStoreId(order.companyDebtorId);
        setOrderId(order.id);
        autoGeneratedRef.current = true;
    }, [initialOrderId, deepLinkOrderQuery.data, isStoreUser]);

    useEffect(() => {
        if (!autoGeneratedRef.current || !initialOrderId) return;
        if (!orderId) return;
        if (generateMut.data || generateMut.isPending) return;
        generate(orderId);
        // eslint-disable-next-line react-hooks/exhaustive-deps
    }, [orderId, initialOrderId]);

    const downloadCsv = () => {
        if (!allLines.length) return;
        const escape = (v: string) => `"${String(v ?? '').replace(/"/g, '""')}"`;
        const rows = [
            [
                'Location Path',
                'Location Code',
                'Product Code',
                'Product Name',
                'Batch',
                'Expiry',
                'Requested',
                'Allocated',
                'Picked',
                'Dispatched',
                'Short',
            ].join(','),
            ...orderedLines.rows.map((l) =>
                [
                    escape(isUnassigned(l) ? 'Location not assigned' : linePath(l)),
                    escape(l.locationCode || (l as any).locationCodePath || ''),
                    escape(l.itemCode || ''),
                    escape(l.productName || l.description || ''),
                    escape(l.batchNumber || ''),
                    escape(l.expiryDate ? new Date(l.expiryDate).toLocaleDateString() : ''),
                    String(l.requestedQuantity ?? ''),
                    String(l.allocatedQuantity ?? ''),
                    String(l.pickedQuantity ?? ''),
                    String(l.dispatchedQuantity ?? ''),
                    String(l.shortageQuantity ?? ''),
                ].join(','),
            ),
        ].join('\n');
        const blob = new Blob([rows], { type: 'text/csv;charset=utf-8;' });
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = `picklist-${selectedOrder?.clientDocumentId || orderId}-${sortBy}.csv`;
        a.click();
        URL.revokeObjectURL(url);
    };

    const renderLine = (l: WarehousePicklistLine, idx: number) => {
        const unassigned = isUnassigned(l);
        return (
            <tr key={`${l.companyStockDetailId || l.saleOrderItemId || l.batchNumber || ''}-${idx}`} className="border-b">
                <td className="py-1">
                    {unassigned ? (
                        <Badge variant="outline" className="border-orange-300 bg-orange-50 text-[10px] text-orange-700">
                            Location not assigned
                        </Badge>
                    ) : (
                        <span className="font-mono text-xs">{linePath(l) || '—'}</span>
                    )}
                </td>
                <td className="py-1 font-mono text-xs">{l.locationCode || (l as any).locationCodePath || '—'}</td>
                <td className="py-1 font-mono text-xs">{l.itemCode || '—'}</td>
                <td className="py-1 font-medium">{l.productName || l.description || l.companyStockDetailId || '—'}</td>
                <td className="py-1 font-mono text-xs">{l.batchNumber || '—'}</td>
                <td className="py-1 text-xs">
                    {l.expiryDate ? new Date(l.expiryDate).toLocaleDateString() : '—'}
                </td>
                <td className="py-1 text-right tabular-nums">{l.requestedQuantity ?? '—'}</td>
                <td className="py-1 text-right tabular-nums">{l.allocatedQuantity ?? '—'}</td>
                <td className="py-1 text-right tabular-nums">{l.pickedQuantity ?? '—'}</td>
                <td className="py-1 text-right tabular-nums">{l.dispatchedQuantity ?? '—'}</td>
                <td className="py-1 text-right tabular-nums">
                    {(l.shortageQuantity ?? 0) > 0 ? (
                        <span className="font-semibold text-red-600">{l.shortageQuantity}</span>
                    ) : (
                        (l.shortageQuantity ?? 0)
                    )}
                </td>
            </tr>
        );
    };

    const isCancelled = HIDDEN_ORDER_STATUSES.includes((selectedOrder?.lifecycleStatus || '').toUpperCase());

    return (
        <PageLoader isLoading={(ordersQuery.isLoading && !initialOrderId) || generateMut.isPending}>
            <div className="space-y-4 px-2">
                <div className="flex flex-wrap items-end gap-3">
                    {!isStoreUser ? (
                        <div className="min-w-[220px]">
                            <Label className="text-xs">Debtor / Store</Label>
                            <div className="mt-1">
                                <SelectPopover
                                    title="Debtor / Store"
                                    onlyTitle="Select store"
                                    selectedValue={storeId}
                                    options={[
                                        { value: '', label: 'All stores' },
                                        ...stores.map((s) => ({ value: s.id, label: s.name || s.tradingAs || s.id })),
                                    ]}
                                    onSelect={(v) => {
                                        setStoreId(String(v || ''));
                                        setOrderId('');
                                        setOrdersLoaded(ORDER_PAGE_SIZE);
                                    }}
                                    selectClass="h-9 text-xs"
                                />
                            </div>
                        </div>
                    ) : (
                        <div className="bg-muted text-muted-foreground flex h-9 items-center rounded-md border px-3 text-xs">
                            Store: {storeName}
                        </div>
                    )}

                    <div className="min-w-[280px] flex-1">
                        <Label className="text-xs">Company Debtor Order</Label>
                        <div className="mt-1">
                            <SelectPopover
                                title="Order"
                                onlyTitle={orders.length ? 'Select an allocated order' : 'No orders'}
                                selectedValue={orderId}
                                options={orders.map((o) => ({
                                    value: o.id,
                                    label: `${o.clientDocumentId || o.id} — ${o.lifecycleStatus} (${o.totalQuantity ?? '?'})`,
                                }))}
                                onSelect={(v) => setOrderId(String(v || ''))}
                                selectClass="h-9 text-xs"
                                isSearching={ordersQuery.isFetching}
                                hasMore={orders.length < orderCount}
                                onLoadMore={() =>
                                    setOrdersLoaded((prev) => Math.min(prev + ORDER_PAGE_SIZE, orderCount))
                                }
                            />
                        </div>
                    </div>

                    <div className="min-w-[160px]">
                        <Label className="text-xs">Sort By</Label>
                        <div className="mt-1">
                            <Select value={sortBy} onValueChange={(v) => setSortBy(v as PicklistSortBy)}>
                                <SelectTrigger className="!h-9 text-xs">
                                    <SelectValue />
                                </SelectTrigger>
                                <SelectContent>
                                    {PICKLIST_SORT_OPTIONS.map((s) => (
                                        <SelectItem key={s} value={s}>
                                            {s === 'AISLE' ? 'Aisle (walking order)' : 'Alphabetical'}
                                        </SelectItem>
                                    ))}
                                </SelectContent>
                            </Select>
                        </div>
                    </div>

                    <Button
                        className="bg-blue-600 text-xs hover:bg-blue-700"
                        onClick={() => generate()}
                        disabled={!orderId || generateMut.isPending || isCancelled}
                        title={isCancelled ? 'This order is cancelled and cannot be picked' : undefined}
                    >
                        {generateMut.isPending ? (
                            <Loader2 className="mr-1 h-4 w-4 animate-spin" />
                        ) : (
                            <ChevronsUpDown className="mr-1 h-4 w-4" />
                        )}
                        Generate Picklist
                    </Button>

                    {/* <Button
                        variant="outline"
                        className="text-xs"
                        onClick={handlePrint}
                        disabled={!allLines.length}
                    >
                        <Printer className="mr-1 h-4 w-4" /> Print Picklist
                    </Button> */}

                    {allLines.length ? (
                        <Button variant="outline" className="text-xs" onClick={downloadCsv}>
                            <FileDown className="mr-1 h-4 w-4" /> CSV
                        </Button>
                    ) : null}
                </div>

                <Separator />

                {!allLines.length ? (
                    <div className="text-muted-foreground rounded-md border border-dashed p-8 text-center text-sm">
                        Select an allocated order and sort order, then generate the warehouse picklist.
                    </div>
                ) : (
                    <div ref={printRef} className="space-y-3">
                        <div className="flex flex-wrap items-center gap-2 text-xs">
                            <Badge variant="secondary">{selectedOrder?.clientDocumentId || orderId || 'Picklist'}</Badge>
                            <Badge variant="outline">
                                Store: {(selectedOrder?.companyDebtorId && storeNameById[selectedOrder.companyDebtorId]) || storeName}
                            </Badge>
                            <Badge variant="outline">Warehouse: {warehouseName}</Badge>
                            <Badge variant="outline">
                                {selectedOrder?.lifecycleStatus || '—'}
                            </Badge>
                            <Badge variant="outline">Sort: {sortBy}</Badge>
                            {selectedOrder ? (
                                <span className="text-muted-foreground flex items-center gap-1">
                                    <CalendarClock className="h-3.5 w-3.5" />
                                    {selectedOrder.scheduledDeliveryDate
                                        ? new Date(selectedOrder.scheduledDeliveryDate).toLocaleDateString()
                                        : 'No delivery date'}
                                </span>
                            ) : null}
                        </div>

                        {picklistSummary ? (
                            <div className="flex flex-wrap items-center gap-2 text-xs">
                                <Badge variant="secondary">Lines: {picklistSummary.lineCount}</Badge>
                                <Badge variant="outline">Requested: {picklistSummary.requestedQuantity}</Badge>
                                <Badge variant="outline">Allocated: {picklistSummary.allocatedQuantity}</Badge>
                                <Badge variant="outline">Picked: {picklistSummary.pickedQuantity}</Badge>
                                {picklistSummary.shortageQuantity > 0 ? (
                                    <Badge variant="destructive">Shortage: {picklistSummary.shortageQuantity}</Badge>
                                ) : (
                                    <Badge variant="outline">Shortage: 0</Badge>
                                )}
                                {orderedLines.unassigned.length > 0 ? (
                                    <Badge className="bg-orange-600 hover:bg-orange-700">
                                        Location not assigned: {orderedLines.unassigned.length}
                                    </Badge>
                                ) : (
                                    <Badge variant="outline">Location not assigned: 0</Badge>
                                )}
                            </div>
                        ) : null}

                        <table className="w-full text-sm">
                            <thead>
                                <tr className="text-muted-foreground border-b text-left text-xs">
                                    <th className="py-1">Location Path</th>
                                    <th className="py-1">Location Code</th>
                                    <th className="py-1">Product Code</th>
                                    <th className="py-1">Product Name</th>
                                    <th className="py-1">Batch</th>
                                    <th className="py-1">Expiry</th>
                                    <th className="py-1 text-right">Requested</th>
                                    <th className="py-1 text-right">Allocated</th>
                                    <th className="py-1 text-right">Picked</th>
                                    <th className="py-1 text-right">Dispatched</th>
                                    <th className="py-1 text-right">Short</th>
                                </tr>
                            </thead>
                            <tbody>{orderedLines.rows.map(renderLine)}</tbody>
                        </table>

                        {!orderedLines.assigned.length ? (
                            <p className="text-muted-foreground text-xs">
                                No inventory is assigned to a warehouse location yet — every line is unassigned.
                            </p>
                        ) : null}
                    </div>
                )}
            </div>
        </PageLoader>
    );
};
export default AislePicklist;
